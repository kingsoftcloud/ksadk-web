import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import postcss from 'postcss';

// Derive the complete reset from our pinned Tailwind instead of maintaining a
// partial copy. Never import the global reset into a consumer-owned document.
export function generateEmbedPreflight() {
  const require = createRequire(import.meta.url);
  const root = postcss.parse(readFileSync(require.resolve('tailwindcss/preflight.css'), 'utf8'));
  root.walkComments(comment => comment.remove());
  root.walkRules(rule => {
    rule.selector = [...new Set(postcss.list.comma(rule.selector).flatMap(selector => {
      if (selector === 'html' || selector === ':host') return [':where(.ksadk-web)'];
      if (selector === '*') return [':where(.ksadk-web)', ':where(.ksadk-web) *'];
      return [`:where(.ksadk-web) ${selector}`];
    }))].join(',\n');
  });
  const layer = postcss.atRule({ name: 'layer', params: 'base' });
  layer.append(root.nodes);
  return '/* Generated by scripts/generate-embed-preflight.mjs. Do not edit. */\n'
    + layer.toString() + '\n';
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(new URL('../src/embed-preflight.css', import.meta.url), generateEmbedPreflight());
}
